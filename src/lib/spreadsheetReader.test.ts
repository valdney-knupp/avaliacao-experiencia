import { describe, it, expect } from 'vitest'
import {
  parseCSV,
  excelSerialToDateBR,
  parseXlsxBuffer,
  parseSpreadsheetFile,
  parseHtmlTable,
} from './spreadsheetReader'
import { buildXlsx, SheetDefinition } from './excelExport'

describe('Spreadsheet Reader (CSV, HTML & XLSX)', () => {
  it('parses CSV with semicolons, commas and quotes', () => {
    const csv1 = `NOME;CPF;CENTRO DE CUSTO;SETOR;FUNÇÃO;DATA INICIAL
João da Silva;12345678909;ESCRITÓRIO;TI;ANALISTA;01/02/2026
Maria Santos;98765432100;BLEND;;PEDREIRO;15/03/2026`

    const res1 = parseCSV(csv1)
    expect(res1.headers.length).toBe(6)
    expect(res1.rows.length).toBe(2)
    expect(res1.rows[0][0]).toBe('João da Silva')
    expect(res1.rows[0][5]).toBe('01/02/2026')
    expect(res1.rows[1][1]).toBe('98765432100')
  })

  it('converts Excel serial date accurately to DD/MM/AAAA', () => {
    // 2026-02-01 in Excel serial = 46054
    const d1 = excelSerialToDateBR(46054)
    expect(d1).toBe('01/02/2026')

    // 2026-12-31 = 46387
    const d2 = excelSerialToDateBR(46387)
    expect(d2).toBe('31/12/2026')
  })

  it('reads uncompressed XLSX generated by buildXlsx', async () => {
    const sheets = [
      {
        name: 'Colaboradores',
        columns: [{ header: 'NOME DO COLABORADOR' }, { header: 'CPF' }, { header: 'DATA' }],
        rows: [['Carlos Souza', '11122233344', { type: 'date' as const, value: '2026-02-01' }]],
      },
    ]

    const bytes = buildXlsx(sheets)
    const parsed = await parseXlsxBuffer(bytes.buffer as ArrayBuffer)

    expect(parsed.headers).toEqual(['NOME DO COLABORADOR', 'CPF', 'DATA'])
    expect(parsed.rows.length).toBe(1)
    expect(parsed.rows[0][0]).toBe('Carlos Souza')
    expect(parsed.rows[0][1]).toBe('11122233344')
    expect(parsed.rows[0][2]).toBe('01/02/2026')
  })

  it('parses HTML tables saved with .xls or .xlsx extension', async () => {
    const html = `<html><body>
      <table>
        <tr><th>NOME</th><th>CPF</th><th>CARGO</th></tr>
        <tr><td>Ana Pereira</td><td>123.456.789-00</td><td>Engenheira</td></tr>
      </table>
    </body></html>`

    const parsed = parseHtmlTable(html)
    expect(parsed).not.toBeNull()
    expect(parsed!.headers).toEqual(['NOME', 'CPF', 'CARGO'])
    expect(parsed!.rows.length).toBe(1)
    expect(parsed!.rows[0]).toEqual(['Ana Pereira', '123.456.789-00', 'Engenheira'])

    // Via parseSpreadsheetFile
    const file = new File([html], 'BD_INCLUSAO-COLABORADOR.xlsx', {
      type: 'application/vnd.ms-excel',
    })
    const fileRes = await parseSpreadsheetFile(file)
    expect(fileRes.headers).toEqual(['NOME', 'CPF', 'CARGO'])
    expect(fileRes.rows[0][0]).toBe('Ana Pereira')
  })

  it('handles multi-sheet workbook reading first worksheet with data', async () => {
    const sheets = [
      {
        name: 'EmptySheet',
        columns: [{ header: 'COL1' }],
        rows: [],
      },
      {
        name: 'DadosObras',
        columns: [{ header: 'COLABORADOR' }, { header: 'NOTA' }],
        rows: [['Lucas Mendes', '4']],
      },
    ]

    const bytes = buildXlsx(sheets)
    const parsed = await parseXlsxBuffer(bytes.buffer as ArrayBuffer)
    expect(parsed.headers).toEqual(['COLABORADOR', 'NOTA'])
    expect(parsed.rows.length).toBe(1)
    expect(parsed.rows[0][0]).toBe('Lucas Mendes')
  })

  it('throws descriptive error on corrupt file without masking the message', async () => {
    const badBuffer = new Uint8Array([0, 1, 2, 3, 4, 5, 6, 7]).buffer
    await expect(parseXlsxBuffer(badBuffer)).rejects.toThrow(/Arquivo XLSX inválido ou corrompido/)
  })

  it('decompresses deflate-raw compressed stream successfully without hanging', async () => {
    // Generate a valid deflate compressed buffer via CompressionStream
    const originalText =
      '<worksheet><sheetData><row r="1"><c r="A1" t="inlineStr"><is><t>TEST_DEFLATE</t></is></c></row></sheetData></worksheet>'
    const encoder = new TextEncoder()
    const rawBytes = encoder.encode(originalText)

    const cs = new CompressionStream('deflate-raw')
    const response = new Response(rawBytes).body?.pipeThrough(cs)
    const compressedBuffer = await new Response(response).arrayBuffer()
    const compressedBytes = new Uint8Array(compressedBuffer)

    // Build a mock minimal ZIP archive with entry using compressionMethod 8 (Deflate)
    const fileName = 'xl/worksheets/sheet1.xml'
    const nameBytes = encoder.encode(fileName)
    const localHeaderLen = 30 + nameBytes.length
    const fileDataLen = compressedBytes.length

    // Construct local header
    const localHeader = new Uint8Array(localHeaderLen)
    const lv = new DataView(localHeader.buffer)
    lv.setUint32(0, 0x04034b50, true)
    lv.setUint16(4, 20, true)
    lv.setUint16(6, 0, true)
    lv.setUint16(8, 8, true) // Deflate compression method
    lv.setUint32(18, fileDataLen, true) // compressed size
    lv.setUint32(22, rawBytes.length, true) // uncompressed size
    lv.setUint16(26, nameBytes.length, true)
    localHeader.set(nameBytes, 30)

    // Central directory header
    const cdHeaderLen = 46 + nameBytes.length
    const cdHeader = new Uint8Array(cdHeaderLen)
    const cv = new DataView(cdHeader.buffer)
    cv.setUint32(0, 0x02014b50, true)
    cv.setUint16(4, 20, true)
    cv.setUint16(6, 20, true)
    cv.setUint16(8, 0, true)
    cv.setUint16(10, 8, true) // Deflate
    cv.setUint32(20, fileDataLen, true)
    cv.setUint32(24, rawBytes.length, true)
    cv.setUint16(28, nameBytes.length, true)
    cv.setUint32(42, 0, true) // local header offset = 0
    cdHeader.set(nameBytes, 46)

    // EOCD
    const eocd = new Uint8Array(22)
    const ev = new DataView(eocd.buffer)
    ev.setUint32(0, 0x06054b50, true)
    ev.setUint16(8, 1, true)
    ev.setUint16(10, 1, true)
    ev.setUint32(12, cdHeaderLen, true)
    ev.setUint32(16, localHeaderLen + fileDataLen, true)

    // Combine all
    const zipBytes = new Uint8Array(localHeaderLen + fileDataLen + cdHeaderLen + 22)
    zipBytes.set(localHeader, 0)
    zipBytes.set(compressedBytes, localHeaderLen)
    zipBytes.set(cdHeader, localHeaderLen + fileDataLen)
    zipBytes.set(eocd, localHeaderLen + fileDataLen + cdHeaderLen)

    const parsed = await parseXlsxBuffer(zipBytes.buffer as ArrayBuffer)
    expect(parsed.headers).toEqual(['TEST_DEFLATE'])
  })

  it('parseSpreadsheetFile respects timeout and handles invalid files cleanly', async () => {
    const file = new File(['corrupted-non-xlsx-data'], 'OBRAS_45D.xlsx', {
      type: 'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet',
    })
    await expect(parseSpreadsheetFile(file, 2000)).rejects.toThrow()
  })

  it('handles realistic multi-row evaluation sheet with shared strings and large row count without blocking', async () => {
    // Generate 500 rows to simulate large spreadsheet import
    const rows = []
    for (let i = 1; i <= 500; i++) {
      rows.push([
        `Colaborador ${i}`,
        `123456789${String(i).padStart(2, '0').slice(-2)}`,
        'OBRAS RESIDENCIAIS',
        '01/02/2026',
        'SIM',
        'SIM',
        'SIM',
        'SIM',
        'EFETIVAR',
        'Excelente desempenho geral.',
      ])
    }

    const sheets = [
      {
        name: 'Avaliações',
        columns: [
          { header: 'NOME DO COLABORADOR' },
          { header: 'CPF' },
          { header: 'CENTRO DE CUSTO' },
          { header: 'DATA ADMISSÃO' },
          { header: 'DISCIPLINA' },
          { header: 'PRODUTIVIDADE' },
          { header: 'RELACIONAMENTO' },
          { header: 'ASSIDUIDADE' },
          { header: 'DECISÃO' },
          { header: 'JUSTIFICATIVA' },
        ],
        rows,
      },
    ]

    const bytes = buildXlsx(sheets)
    const start = Date.now()
    const parsed = await parseXlsxBuffer(bytes.buffer as ArrayBuffer)
    const elapsed = Date.now() - start

    expect(parsed.headers.length).toBe(10)
    expect(parsed.rows.length).toBe(500)
    expect(parsed.rows[0][0]).toBe('Colaborador 1')
    expect(parsed.rows[499][0]).toBe('Colaborador 500')
    // Ensure processing completes quickly without loop freeze
    expect(elapsed).toBeLessThan(5000)
  })

  it('handles zip entries compressed with deflate and protects against infinite EOCD searching', async () => {
    // Large buffer with arbitrary bytes and trailing random values (not standard zip)
    const randomBytes = new Uint8Array(80000)
    for (let i = 0; i < randomBytes.length; i++) {
      randomBytes[i] = (i * 37) & 0xff
    }
    // Attempting parseXlsxBuffer must fail cleanly, not loop forever
    await expect(parseXlsxBuffer(randomBytes.buffer as ArrayBuffer)).rejects.toThrow()
  })

  it('filters out empty rows and trims whitespace safely in parseCSV and parseXlsxBuffer', async () => {
    // CSV with empty rows, rows with trailing semicolons and trailing commas
    const csvWithEmptyLines = `NOME;CARGO;DATA\n\nJoão Silva;Analista;01/01/2026\n;;;\n   ;   ;   \nMaria Souza;Coordenadora;10/01/2026\n\n`
    const parsedCsv = parseCSV(csvWithEmptyLines)
    expect(parsedCsv.headers).toEqual(['NOME', 'CARGO', 'DATA'])
    expect(parsedCsv.rows).toHaveLength(2)
    expect(parsedCsv.rows[0]).toEqual(['João Silva', 'Analista', '01/01/2026'])
    expect(parsedCsv.rows[1]).toEqual(['Maria Souza', 'Coordenadora', '10/01/2026'])

    // XLSX with empty / sparse rows
    const sheets: SheetDefinition[] = [
      {
        name: 'Obras 90D',
        columns: [
          { header: 'NOME DO COLABORADOR' },
          { header: 'DATA DA AVALIAÇÃO' },
          { header: 'AVALIADOR' },
          { header: 'DECISÃO' },
          { header: 'DISCIPLINA' },
        ],
        rows: [
          ['Carlos Alberto', '15/01/2026', 'Gestor 1', 'Efetivar', 'Atende'],
          ['', '', '', '', ''], // empty row
          ['Fernanda Lima', '16/01/2026', '', 'Efetivar', ''], // partially filled
        ],
      },
    ]

    const bytes = buildXlsx(sheets)
    const parsedXlsx = await parseXlsxBuffer(bytes.buffer as ArrayBuffer)
    expect(parsedXlsx.headers).toEqual([
      'NOME DO COLABORADOR',
      'DATA DA AVALIAÇÃO',
      'AVALIADOR',
      'DECISÃO',
      'DISCIPLINA',
    ])
    expect(parsedXlsx.rows).toHaveLength(2)
    expect(parsedXlsx.rows[0][0]).toBe('Carlos Alberto')
    expect(parsedXlsx.rows[1][0]).toBe('Fernanda Lima')
  })
})
